/**
 * Writes deploy/migrations/0000-baseline.sql: the full schema of
 * packages/shared/src/db/schema.ts as `drizzle-kit generate` renders it for an
 * empty database. No database connection is needed.
 *
 *   pnpm --filter @terragon/migrate generate-baseline
 *
 * The baseline is an applied migration like any other: once a database has
 * recorded it, editing it is drift and the runner refuses to continue. Schema
 * changes after the baseline are new files in deploy/migrations.
 */
import { execFileSync } from "node:child_process";
import {
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE_DIR = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const REPO_ROOT = path.resolve(PACKAGE_DIR, "..", "..");
const SCHEMA = path.join(REPO_ROOT, "packages/shared/src/db/schema.ts");
const TARGET = path.join(REPO_ROOT, "deploy/migrations/0000-baseline.sql");

const HEADER = `-- migrate:baseline
--
-- Full schema snapshot of packages/shared/src/db/schema.ts, generated by
-- packages/migrate/scripts/generate-baseline.ts (drizzle-kit generate against
-- an empty schema). The runner applies it only to a database with no tables in
-- public; a database that already has the schema records it with
--   tsx deploy/migrate.ts --mark-applied 0000-baseline
-- Do not edit: once recorded anywhere, a changed checksum is drift.

`;

function main(): void {
  const out = mkdtempSync(path.join(os.tmpdir(), "automata-baseline-"));
  try {
    execFileSync(
      path.join(PACKAGE_DIR, "node_modules/.bin/drizzle-kit"),
      [
        "generate",
        "--dialect=postgresql",
        `--schema=${SCHEMA}`,
        `--out=${out}`,
      ],
      { cwd: PACKAGE_DIR, stdio: ["ignore", "ignore", "inherit"] },
    );
    const generated = readdirSync(out).filter((name) => name.endsWith(".sql"));
    if (generated.length !== 1 || !generated[0]) {
      throw new Error(
        `expected exactly one generated .sql file, found ${generated.length}`,
      );
    }
    const body = readFileSync(path.join(out, generated[0]), "utf8").replace(
      /\r\n/g,
      "\n",
    );
    writeFileSync(TARGET, HEADER + body.trimEnd() + "\n");
    console.log(`wrote ${path.relative(REPO_ROOT, TARGET)}`);
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}

main();

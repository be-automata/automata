import {
  isBoxTestServicesRepo,
  receivesBoxTestServices,
  TEST_DATABASE_ADMIN_URL,
} from "./box-test-services";
import type { RunLane } from "./run-lane";
import type { AgentRunInput } from "./types";

/**
 * A cell's test database (#707, OD-1 option A): for a run of a repo the box's
 * TEST_SERVICES_REPOS lists, a Postgres 16 starts INSIDE the cell, listening
 * on the cell's own loopback only, and the agent gets
 * `TEST_DATABASE_ADMIN_URL` for a LOGIN CREATEDB NOSUPERUSER role, as the box
 * hands its runs (install-test-postgres.sh). Nothing reaches the box: the
 * database lives and dies with the cell, so no sweep is needed.
 *
 * Every step runs as the cell's only user (uid 10001: no sudo, and
 * no_new_privileges is set), so the cluster belongs to the agent's own uid;
 * the role exists for parity with the box, not as a wall against the agent.
 *
 * The password is generated by the worker per cell and never logged. It
 * reaches the cell in a copyIn body only (into a 0700 dir, removed once the
 * role is made), never in an exec argv (execd logs argv), and the agent gets
 * the URL through the same settings `env` block as the repo env (#706).
 * Constants and argvs only: the worker's steps are in cell-run.ts.
 */

export const CELL_TEST_DB_ENV = TEST_DATABASE_ADMIN_URL;
/** The Postgres 16 server binaries the cell image installs (Ubuntu `postgresql-16`, OD-2). */
export const CELL_PG_BIN = "/usr/lib/postgresql/16/bin";
/** Data dir, socket and server log; created 0700 by the first step, so it must not exist yet. */
export const CELL_TEST_DB_DIR = "/tmp/automata-test-db";
export const CELL_TEST_DB_PASSWORD_FILE = `${CELL_TEST_DB_DIR}/pw`;
/** The box's port (install-test-postgres.sh), on the cell's own loopback. */
export const CELL_TEST_DB_PORT = 25432;
export const CELL_TEST_DB_ROLE = "automata_test";

/** Fails when the dir exists: a cell starts one database, never reuses one. */
export const CELL_TEST_DB_MKDIR_ARGV: readonly string[] = [
  "/bin/mkdir",
  "-m",
  "700",
  CELL_TEST_DB_DIR,
];

/**
 * initdb (local peer for the cell's own user, scram on TCP), then a start that
 * does not wait: readiness is the worker's bounded `pg_isready` loop. Durability
 * is off: a throwaway database for test suites. initdb's output goes to a file
 * and only its tail to stderr on a failure.
 * `bash -c <script> cell-test-db`.
 */
export const CELL_TEST_DB_START_SH = [
  "set -eu",
  "PATH=/usr/bin:/bin",
  `d=${CELL_TEST_DB_DIR}`,
  `if ! ${CELL_PG_BIN}/initdb -D "$d/data" -U agent --auth-local=peer --auth-host=scram-sha-256 -E UTF8 --locale=C.UTF-8 --no-instructions >"$d/initdb.log" 2>&1; then`,
  '  tail -n 20 "$d/initdb.log" >&2',
  "  exit 1",
  "fi",
  `exec ${CELL_PG_BIN}/pg_ctl -D "$d/data" -l "$d/server.log" -W -o "-c listen_addresses=127.0.0.1 -c port=${CELL_TEST_DB_PORT} -c unix_socket_directories=$d -c max_connections=50 -c shared_buffers=64MB -c fsync=off -c synchronous_commit=off -c full_page_writes=off" start`,
].join("\n");

/** Exit 0 once the server accepts connections on the loopback port. */
export const CELL_TEST_DB_READY_ARGV: readonly string[] = [
  `${CELL_PG_BIN}/pg_isready`,
  "-q",
  "-h",
  "127.0.0.1",
  "-p",
  String(CELL_TEST_DB_PORT),
  "-d",
  "postgres",
];

/**
 * The role, its password read by psql itself from the staged file (no argv,
 * no env), with error statements kept out of the server log; then the file is
 * removed whether or not psql worked. `\set VERBOSITY terse` keeps the
 * statement text out of psql's own error output.
 * `bash -c <script> cell-test-db`.
 */
export const CELL_TEST_DB_ROLE_SH = [
  "set -eu",
  "PATH=/usr/bin:/bin",
  // An absent or empty file would make a role with no password.
  `[ -s ${CELL_TEST_DB_PASSWORD_FILE} ] || { echo "cell-test-db: no password file" >&2; exit 65; }`,
  "rc=0",
  `${CELL_PG_BIN}/psql -X -q -v ON_ERROR_STOP=1 -h ${CELL_TEST_DB_DIR} -p ${CELL_TEST_DB_PORT} -U agent -d postgres <<'SQL' || rc=$?`,
  "\\set VERBOSITY terse",
  `\\set pw \`cat ${CELL_TEST_DB_PASSWORD_FILE}\``,
  "SET log_min_error_statement = panic;",
  `CREATE ROLE ${CELL_TEST_DB_ROLE} LOGIN CREATEDB NOSUPERUSER NOCREATEROLE NOREPLICATION NOBYPASSRLS CONNECTION LIMIT 40 PASSWORD :'pw';`,
  "SQL",
  `rm -f -- ${CELL_TEST_DB_PASSWORD_FILE}`,
  'exit "$rc"',
].join("\n");

/**
 * After a failed start: remove the staged password and stop a server that may
 * be up, ignoring what is not there. `bash -c <script>`; its result is ignored.
 */
export const CELL_TEST_DB_STOP_SH = [
  "PATH=/usr/bin:/bin",
  `rm -f -- ${CELL_TEST_DB_PASSWORD_FILE}`,
  `${CELL_PG_BIN}/pg_ctl -D ${CELL_TEST_DB_DIR}/data -m immediate stop >/dev/null 2>&1`,
].join("\n");

const PASSWORD = /^[0-9a-f]{32,}$/;

/** The agent's URL. The password must be the worker's hex (as the box's): it is never quoted or escaped. */
export function cellTestDbUrl(password: string): string {
  if (!PASSWORD.test(password)) {
    throw new Error("cell test database password is not 32+ hex chars");
  }
  return `postgresql://${CELL_TEST_DB_ROLE}:${password}@127.0.0.1:${CELL_TEST_DB_PORT}/postgres`;
}

/**
 * What a cell run does about a test database: `start` one for a run the box
 * would give its test services (receivesBoxTestServices) of a repo its file
 * lists (TEST_SERVICES_REPOS, read on every call); `owner` when the owner's
 * repo env already sets TEST_DATABASE_ADMIN_URL (theirs wins, as on the box,
 * and no server is started); `off` otherwise.
 */
export function planCellTestDb(opts: {
  input: Pick<AgentRunInput, "repoFullName" | "reviewAgent" | "selfHeal">;
  lane: RunLane;
  /** The repo env the agent gets (cellRepoEnv's `env`). */
  repoEnv: Record<string, string>;
  /** The box test-services file; default BOX_TEST_SERVICES_ENV_PATH. */
  envPath?: string;
}): "start" | "owner" | "off" {
  if (
    !receivesBoxTestServices(opts.input, opts.lane) ||
    !isBoxTestServicesRepo(opts.input.repoFullName, opts.envPath)
  ) {
    return "off";
  }
  return Object.hasOwn(opts.repoEnv, CELL_TEST_DB_ENV) ? "owner" : "start";
}
